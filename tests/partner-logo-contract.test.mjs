test("human rollback reconstructs the immutable original files through a new bounded receipt", t => {
  const f = fixture(t, "authorized_public_sponsor", ["nicolas", "studio-seven"]);
  const published = f.writeCandidate();
  const plan = logoRollbackPlan(f.root, published, f.grant.payload.bundle_sha256);
  assert.equal(git(f.root, "status", "--porcelain"), "");
  for (const [path, bytes] of plan.restore) {
    if (bytes === null) unlinkSync(join(f.root, path));
    else writeFileSync(join(f.root, path), bytes);
  }
  writeFileSync(join(f.root, plan.receiptPath), canonicalJson(plan.receipt) + "\n");
  git(f.root, "add", "."); git(f.root, "commit", "-m", "Synthetic governed inverse");
  const head = git(f.root, "rev-parse", "HEAD");
  assert.equal(validateLogoCandidate(f.root, { base: published, head }).mode, "partner-logo-human-rollback-candidate");
  assert.equal(readFileSync(join(f.root, REGISTRY_PATH), "utf8").replace(/\r\n/gu, "\n"), registry.replace(/\r\n/gu, "\n"));
  assert.equal(existsSync(join(f.root, PARTNERS.nicolas.asset)), false);
});

